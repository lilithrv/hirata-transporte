    private void cargarComboEstado() {
        cmbEstado.removeAllItems();
        cmbEstado.addItem("Seleccionar");
        cmbEstado.addItem("Activo");
        cmbEstado.addItem("Inactivo");
        cmbEstado.addItem("En Mantenimiento");
    }

    private void cargarComboTipo() {
        TipoEquipoDAO dao = new TipoEquipoDAO();
        listaTipos = dao.listarTodos();
        cmbTipo.removeAllItems();
        cmbTipo.addItem("Seleccionar");
        for (TipoEquipo t : listaTipos) {
            cmbTipo.addItem(t.getNombre());
        }
    }

    private void cargarComboResponsable() {
        UsuarioDAO dao = new UsuarioDAO();
        listaResponsables = dao.listarResponsablesEquipo();
        cmbResponsable.removeAllItems();
        cmbResponsable.addItem("Sin asignar");
        for (Usuario u : listaResponsables) {
            cmbResponsable.addItem(u.getNombreUsuario());
        }
    }

    private void cargarDatos() {
        // Seleccionar el tipo en el combo
        for (int i = 0; i < listaTipos.size(); i++) {
            if (listaTipos.get(i).getIdTipoEquipo() == equipo.getTipoEquipo().getIdTipoEquipo()) {
                cmbTipo.setSelectedIndex(i + 1); // +1 por el "Seleccionar"
                break;
            }
        }

        txtMarca.setText(equipo.getMarca());
        txtModelo.setText(equipo.getModelo());
        txtSerie.setText(equipo.getNumeroSerie());
        cmbEstado.setSelectedItem(equipo.getEstado());

        // Responsable
        for (int i = 0; i < listaResponsables.size(); i++) {
            if (listaResponsables.get(i).getIdUsuario() == equipo.getIdResponsable()) {
                cmbResponsable.setSelectedIndex(i + 1); // +1 por el "Sin asignar"
                break;
            }
        }

        // Fecha adquisicion
        if (equipo.getFechaAdquisicion() != null && !equipo.getFechaAdquisicion().isEmpty()) {
            try {
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
                Date fecha = sdf.parse(equipo.getFechaAdquisicion());
                spinnerFecha.setValue(fecha);
            } catch (ParseException e) {
                System.err.println("Error al cargar fecha: " + e.getMessage());
            }
        }
    }

