    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        // ── Validaciones ──────────────────────────────────────────
        int indexTipo = cmbTipo.getSelectedIndex();
        if (indexTipo == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un tipo de equipo.");
            return;
        }
        TipoEquipo tipoSeleccionado = listaTipos.get(indexTipo - 1);

        String marca = txtMarca.getText().trim();
        if (marca.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la marca.");
            return;
        }
        String modelo = txtModelo.getText().trim();
        if (modelo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el modelo.");
            return;
        }
        String serie = txtSerie.getText().trim();
        if (serie.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el número de serie.");
            return;
        }
        String estado = (String) cmbEstado.getSelectedItem();
        if (estado == null || estado.equals("Seleccionar")) {
            JOptionPane.showMessageDialog(this, "Seleccione un estado.");
            return;
        }

        // ── Responsable (opcional) ────────────────────────────────
        int indexResp = cmbResponsable.getSelectedIndex();

        // ── Fecha adquisicion ─────────────────────────────────────
        Date fechaSeleccionada = (Date) spinnerFecha.getValue();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String fechaAdquisicion = sdf.format(fechaSeleccionada);

        // ── Construir objeto con el mismo ID ──────────────────────
        equipo.setTipoEquipo(tipoSeleccionado);
        equipo.setMarca(marca);
        equipo.setModelo(modelo);
        equipo.setNumeroSerie(serie);
        equipo.setEstado(estado);
        equipo.setFechaAdquisicion(fechaAdquisicion);

        if (indexResp > 0) {
            equipo.setIdResponsable(listaResponsables.get(indexResp - 1).getIdUsuario());
        } else {
            equipo.setIdResponsable(0); // sin asignar
        }

        // ── Actualizar ────────────────────────────────────────────
        EquipoOficinaDAO dao = new EquipoOficinaDAO();
        if (dao.actualizar(equipo)) {
            JOptionPane.showMessageDialog(this, "Equipo actualizado correctamente.");
            confirmado = true;
            dispose();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Error al actualizar. Verifique que el N° de serie no esté repetido.");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

